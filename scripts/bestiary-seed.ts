// Writes the seed migration for the Nimble GM's Guide monsters (`data/nimble/bestiary.ts`)
// into the shared NPC pool as official rows. Re-running it rewrites the same migration file;
// the upsert on `slug` updates rows that already exist.
//
//   npm run seed:bestiary

import { readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { BESTIARY } from '../data/nimble/bestiary'
import { bestiaryRows } from '../utils/bestiary'

const DIR = join(import.meta.dirname, '..', 'supabase', 'migrations')
const SUFFIX = '_nimble_gmg_bestiary.sql'

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`

function timestamp() {
  return new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14)
}

const existing = readdirSync(DIR).find((f) => f.endsWith(SUFFIX))
const file = join(DIR, existing ?? `${timestamp()}${SUFFIX}`)

const rows = bestiaryRows(BESTIARY)
const values = rows
  .map(
    (r) =>
      `  (${[
        quote(r.system),
        quote(r.kind),
        quote(r.name),
        quote(r.level),
        quote(r.slug),
        quote(r.source),
        quote(r.source_ref),
        `${quote(JSON.stringify(r.stat_block))}::jsonb`,
      ].join(', ')})`,
  )
  .join(',\n')

const sql = `-- Official Nimble monsters from the GM's Guide 1.0: the bestiary, the legendary
-- monsters and the sample adventure's bosses (${rows.length} rows).
-- Generated by \`npm run seed:bestiary\` from data/nimble/bestiary.ts; edit the data, not this file.
--
-- Lantern is an independent product published under the Nimble 3rd Party Creator License
-- and is not affiliated with Nimble Co. Nimble © 2025 Nimble Co.

insert into public.npcs (system, kind, name, level, slug, source, source_ref, stat_block)
values
${values}
on conflict (slug) do update set
  system = excluded.system,
  kind = excluded.kind,
  name = excluded.name,
  level = excluded.level,
  source = excluded.source,
  source_ref = excluded.source_ref,
  stat_block = excluded.stat_block,
  updated_at = now();
`

writeFileSync(file, sql)
console.log(`Wrote ${rows.length} monsters to ${file}`)
